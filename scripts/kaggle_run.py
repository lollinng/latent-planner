#!/usr/bin/env python3
"""Run training/eval jobs on a free Kaggle T4 (private script kernel), then fetch and merge the results.

The code (latent_planner/ + the fixed task files) is embedded in the kernel as a base64 tarball, so the repo
doesn't need to be public. The kernel regenerates the dataset from its seeds (12 s) and prints sha256 hashes so
we can check it matches the local data. Only logs, summaries, CSVs and checkpoints are written to the kernel
output; working files live in /tmp on the Kaggle machine.

    .venv/bin/python scripts/kaggle_run.py push  --slug lp-lam-sweep --jobs "lam0.01_s0=--lam 0.01 --seed 0" ...
    .venv/bin/python scripts/kaggle_run.py wait  --slug lp-lam-sweep
    .venv/bin/python scripts/kaggle_run.py merge --slug lp-lam-sweep

Kernel metadata (private, GPU + internet, T4 forced because Kaggle's PyTorch dropped P100) follows the setup in
a private Kaggle runner. Needs ~/.kaggle/kaggle.json.
"""
from __future__ import annotations

import argparse
import base64
import csv
import io
import json
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KAGGLE = str(ROOT / ".venv" / "bin" / "kaggle")
JOBS_DIR = ROOT / "kaggle_jobs"

KERNEL_TEMPLATE = r'''# LatentPlanner jobs on Kaggle (auto-generated by scripts/kaggle_run.py)
import base64, hashlib, io, os, shutil, subprocess, sys, tarfile, time
PAYLOAD = "__PAYLOAD__"
JOBS = __JOBS__
TAG = "__TAG__"
DATA_CMDS = __DATA_CMDS__
EVAL_CMDS = __EVAL_CMDS__
WORK, OUT = "/tmp/lp", "/kaggle/working"
os.makedirs(WORK, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz").extractall(WORK)
os.chdir(WORK)

def sh(cmd):
    print("+ " + cmd, flush=True)
    t = time.time()
    r = subprocess.run(cmd, shell=True)
    print(f"exit {r.returncode} after {time.time() - t:.0f}s", flush=True)
    return r.returncode

import torch
print("torch", torch.__version__, "cuda", torch.cuda.is_available(),
      torch.cuda.get_device_name(0) if torch.cuda.is_available() else "no gpu", flush=True)
for c in DATA_CMDS:
    sh(c)

def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 24), b""):
            h.update(b)
    return h.hexdigest()[:16]

import glob
for p in sorted(glob.glob("data/*/frames.npy") + glob.glob("data/*/pos.npy") + glob.glob("data/*/actions.npy")):
    print("SHA256", p, sha(p), flush=True)

def save_outputs():
    for name, _ in JOBS:
        src = os.path.join("runs", name)
        if os.path.isdir(src):
            shutil.copytree(src, os.path.join(OUT, "runs", name), dirs_exist_ok=True)
    os.makedirs(os.path.join(OUT, "results"), exist_ok=True)
    for f in ["eval.csv", "analysis.csv", "eval_push.csv"]:
        if os.path.exists(os.path.join("results", f)):
            shutil.copy(os.path.join("results", f), os.path.join(OUT, "results", f))
    if os.path.isdir("results/eval"):
        shutil.copytree("results/eval", os.path.join(OUT, "results", "eval"), dirs_exist_ok=True)

for name, args in JOBS:
    os.makedirs(f"runs/{name}", exist_ok=True)
    sh(f"python -m latent_planner.train --out runs/{name} {args} > runs/{name}/stdout.txt 2>&1")
    sh(f"tail -3 runs/{name}/stdout.txt")
    for c in EVAL_CMDS:
        sh(c.format(name=name, tag=TAG))
    save_outputs()  # after every job, so a timeout still leaves results
print("ALL_JOBS_DONE", flush=True)
'''


def run(cmd: list[str]) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, capture_output=True, text=True)


def username() -> str:
    tok = Path.home() / ".kaggle" / "kaggle.json"
    if tok.is_file() and "username" in (d := json.loads(tok.read_text())):
        return d["username"]
    r = run([KAGGLE, "config", "view"])  # newer token formats carry no username
    for line in (r.stdout + r.stderr).splitlines():
        if "username:" in line:
            return line.split("username:", 1)[1].strip()
    sys.exit("could not determine the Kaggle username")


def payload() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for p in sorted((ROOT / "latent_planner").glob("*.py")):
            tar.add(p, arcname=f"latent_planner/{p.name}")
        for name in ["tasks_test.json", "tasks_tune.json", "push_tasks_test.json", "push_tasks_tune.json"]:
            if (ROOT / "results" / name).exists():
                tar.add(ROOT / "results" / name, arcname=f"results/{name}")
    return base64.b64encode(buf.getvalue()).decode()


TWOROOM_DATA = ["python -m latent_planner.data --episodes 2000 --seed 0 --out data/train",
                "python -m latent_planner.data --episodes 200 --seed 1 --out data/val"]
TWOROOM_EVAL = ["python -m latent_planner.eval --runs runs/{name} --taskset test --tag {tag} --running-w 1.0",
                "python -m latent_planner.analyze --runs runs/{name}"]
PUSH_DATA = ["python -m latent_planner.data --scene push --episodes 2000 --seed 10 --out data/push_train",
             "python -m latent_planner.data --scene push --episodes 200 --seed 11 --out data/push_val"]
PUSH_EVAL_TUNE = ["python -m latent_planner.eval_push --runs runs/{name} --taskset tune --tag {tag}"]


def push(slug: str, jobs: list[tuple[str, str]], tag: str, scene: str = "tworoom",
         data_cmds: list[str] | None = None, eval_cmds: list[str] | None = None) -> None:
    wd = JOBS_DIR / slug
    wd.mkdir(parents=True, exist_ok=True)
    d0, e0 = (PUSH_DATA, PUSH_EVAL_TUNE) if scene == "push" else (TWOROOM_DATA, TWOROOM_EVAL)
    data_cmds, eval_cmds = data_cmds or d0, eval_cmds or e0
    src = (KERNEL_TEMPLATE.replace("__PAYLOAD__", payload()).replace("__JOBS__", repr(jobs))
           .replace("__TAG__", tag).replace("__DATA_CMDS__", repr(data_cmds)).replace("__EVAL_CMDS__", repr(eval_cmds)))
    (wd / "script.py").write_text(src)
    (wd / "jobs.json").write_text(json.dumps({"jobs": jobs, "tag": tag, "pushed": time.strftime("%F %T")}, indent=1))
    (wd / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{username()}/{slug}", "title": slug, "code_file": "script.py", "language": "python",
        "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
        "machine_shape": "NvidiaTeslaT4"}, indent=1))
    r = run([KAGGLE, "kernels", "push", "-p", str(wd), "--accelerator", "NvidiaTeslaT4"])
    print(r.stdout.strip(), r.stderr.strip())
    if r.returncode != 0:
        sys.exit("push failed")


def wait(slug: str, poll: int, timeout: int) -> str:
    kid = f"{username()}/{slug}"
    t0 = time.time()
    while time.time() - t0 < timeout:
        r = run([KAGGLE, "kernels", "status", kid])
        line = (r.stdout + r.stderr).strip().splitlines()[-1] if (r.stdout or r.stderr) else ""
        print(f"[{int(time.time() - t0)}s] {line}", flush=True)
        low = line.lower()
        if any(k in low for k in ("complete", "error", "cancel")):
            break
        time.sleep(poll)
    out = JOBS_DIR / slug / "out"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    r = run([KAGGLE, "kernels", "output", kid, "-p", str(out)])
    print(r.stdout.strip()[-500:], r.stderr.strip()[-500:])
    return line


def merge(slug: str) -> None:
    """Copy the fetched runs into runs/ and append their CSV rows to results/ (skipping rows already there)."""
    out = JOBS_DIR / slug / "out"
    for d in sorted((out / "runs").glob("*")):
        dst = ROOT / "runs" / d.name
        if dst.exists():
            print(f"runs/{d.name} exists locally, not overwriting")
            continue
        shutil.copytree(d, dst)
        print(f"copied runs/{d.name}")
    for name in ["eval.csv", "analysis.csv", "eval_push.csv"]:
        src, dst = out / "results" / name, ROOT / "results" / name
        if not src.exists():
            continue
        have = set(dst.read_text().splitlines()) if dst.exists() else set()
        rows = src.read_text().splitlines()
        new = [r for r in rows[1:] if r not in have]
        with open(dst, "a") as f:
            for r in new:
                f.write(r + "\n")
        print(f"results/{name}: +{len(new)} rows")
    if (out / "results" / "eval").exists():
        shutil.copytree(out / "results" / "eval", ROOT / "results" / "eval", dirs_exist_ok=True)
    logs = list(out.glob("*.log"))
    if logs:
        shutil.copy(logs[0], ROOT / "results" / f"kaggle_{slug}.log")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=["push", "wait", "merge"])
    ap.add_argument("--slug", required=True)
    ap.add_argument("--jobs", nargs="*", default=[], help='"name=train args" entries')
    ap.add_argument("--tag", default="main")
    ap.add_argument("--scene", choices=["tworoom", "push"], default="tworoom")
    ap.add_argument("--data-cmd", action="append", default=None, help="override the data commands (repeatable)")
    ap.add_argument("--eval-cmd", action="append", default=None,
                    help="override the per-job eval commands; {name} and {tag} are filled in (repeatable)")
    ap.add_argument("--poll", type=int, default=60)
    ap.add_argument("--timeout", type=int, default=6 * 3600)
    a = ap.parse_args()
    if a.action == "push":
        jobs = [tuple(j.split("=", 1)) for j in a.jobs]
        assert jobs, "no jobs"
        push(a.slug, jobs, a.tag, a.scene, a.data_cmd, a.eval_cmd)
    elif a.action == "wait":
        print(wait(a.slug, a.poll, a.timeout))
    else:
        merge(a.slug)


if __name__ == "__main__":
    main()
