#!/usr/bin/env python3
"""Run training/eval jobs on a free Google Colab T4 through the official Colab CLI, then fetch and merge the results.

Mirrors scripts/kaggle_run.py: the code (latent_planner/ + the fixed task files) is embedded in the job script as a
base64 tarball, so the repo doesn't need to be public. The runtime regenerates the dataset from its seeds and prints
sha256 hashes so we can check it matches the local data. Only logs, summaries, CSVs and checkpoints are packed for
download; working files live in /tmp on the Colab machine.

How the steps map onto the CLI (google-colab-cli in .colab-venv/, see docs/COLAB.md):
    push  = `colab new -s <slug> --gpu T4`, then `colab exec -s <slug> -f script.py --timeout 0` started in the
            background (its output goes to colab_jobs/<slug>/exec.log). The jobs run as one notebook cell, so the
            kernel stays busy and Colab doesn't idle the VM out; if the local process dies, the cell keeps running.
    wait  = poll /content/lp_status.txt with `colab download` until ALL_JOBS_DONE or FAILED, download
            /content/lp_out.tar.gz into colab_jobs/<slug>/out, then `colab stop` the VM (unless --keep).
    merge = same as kaggle_run.py: copy runs/<name> into runs/ (never overwriting) and append new CSV rows.
No `colab ssh`: free runtimes forbid remote shells, so everything goes through the notebook kernel and file API.

    python3 scripts/colab_run.py login                 # one time: prints a Google sign-in URL
    python3 scripts/colab_run.py login --code CODE     # then paste the code Google shows
    python3 scripts/colab_run.py check                 # lists sessions: proves the sign-in works
    python3 scripts/colab_run.py push  --slug lp-lam --jobs "lam0.01_s0=--lam 0.01 --seed 0" ...
    python3 scripts/colab_run.py wait  --slug lp-lam
    python3 scripts/colab_run.py merge --slug lp-lam
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tarfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from kaggle_run import PUSH_DATA, PUSH_EVAL_TUNE, TWOROOM_DATA, TWOROOM_EVAL, payload  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
COLAB_VENV = ROOT / ".colab-venv"
COLAB = COLAB_VENV / "bin" / "colab"
COLAB_PY = COLAB_VENV / "bin" / "python"
JOBS_DIR = ROOT / "colab_jobs"
LOGIN_PENDING = JOBS_DIR / ".login-pending.json"
REMOTE_STATUS, REMOTE_TAR = "/content/lp_status.txt", "/content/lp_out.tar.gz"
# This laptop (WSL) has no OS keyring, so the CLI's OAuth token would not persist and every command would ask to sign
# in again. keyrings.alt's file backend stores it in ~/.local/share/python_keyring/keyring_pass.cfg (mode 600).
# Set PYTHON_KEYRING_BACKEND yourself to use a different backend.
KEYRING_BACKEND = "keyrings.alt.file.PlaintextKeyring"

JOB_TEMPLATE = r'''# LatentPlanner jobs on Colab (auto-generated by scripts/colab_run.py)
import base64, glob, hashlib, io, os, shutil, subprocess, sys, tarfile, time, traceback
PAYLOAD = "__PAYLOAD__"
JOBS = __JOBS__
TAG = "__TAG__"
DATA_CMDS = __DATA_CMDS__
EVAL_CMDS = __EVAL_CMDS__
WORK, OUT = "/tmp/lp", "/content/lp_out"
STATUS, TARBALL = "__STATUS__", "__TARBALL__"
for d in (WORK, OUT):
    shutil.rmtree(d, ignore_errors=True)
    os.makedirs(d)
os.chdir(WORK)
os.environ["PATH"] = os.path.dirname(sys.executable) + os.pathsep + os.environ.get("PATH", "")  # `python` = kernel's
LOG = open(os.path.join(OUT, "colab.log"), "a", buffering=1)

def log(msg):
    print(msg, flush=True)
    LOG.write(msg + "\n")

def status(msg):
    log("STATUS " + msg)
    with open(STATUS + ".tmp", "w") as f:
        f.write(time.strftime("%F %T ") + msg + "\n")
    os.replace(STATUS + ".tmp", STATUS)

def sh(cmd):
    log("+ " + cmd)
    t = time.time()
    p = subprocess.Popen(cmd, shell=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in p.stdout:
        log(line.rstrip("\n"))
    rc = p.wait()
    log(f"exit {rc} after {time.time() - t:.0f}s")
    return rc

def train(cmd, stdout_file, label):
    """Run a training command whose output goes to a file; every 60 s put its last line in the status file."""
    log("+ " + cmd)
    t = time.time()
    p = subprocess.Popen(cmd, shell=True)
    while p.poll() is None:
        time.sleep(60)
        last = ""
        if os.path.exists(stdout_file):
            with open(stdout_file, errors="replace") as f:
                lines = [l.strip() for l in f.readlines()[-5:] if l.strip()]
            last = lines[-1][:200] if lines else ""
        status(f"{label} {time.time() - t:.0f}s | {last}")
    log(f"exit {p.returncode} after {time.time() - t:.0f}s")
    return p.returncode

def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 24), b""):
            h.update(b)
    return h.hexdigest()[:16]

def save_outputs():
    for name, _ in JOBS:
        src = os.path.join(WORK, "runs", name)
        if os.path.isdir(src):
            shutil.copytree(src, os.path.join(OUT, "runs", name), dirs_exist_ok=True)
    os.makedirs(os.path.join(OUT, "results"), exist_ok=True)
    for f in ["eval.csv", "analysis.csv", "eval_push.csv"]:
        if os.path.exists(os.path.join(WORK, "results", f)):
            shutil.copy(os.path.join(WORK, "results", f), os.path.join(OUT, "results", f))
    if os.path.isdir(os.path.join(WORK, "results", "eval")):
        shutil.copytree(os.path.join(WORK, "results", "eval"), os.path.join(OUT, "results", "eval"), dirs_exist_ok=True)

def pack():
    with tarfile.open(TARBALL + ".tmp", "w:gz") as tar:
        for n in sorted(os.listdir(OUT)):
            tar.add(os.path.join(OUT, n), arcname=n)
    os.replace(TARBALL + ".tmp", TARBALL)

final = "FAILED before the first job"
status("starting")
try:
    tar = tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz")
    try:
        tar.extractall(WORK, filter="data")
    except TypeError:  # Python without extraction filters
        tar.extractall(WORK)
    import torch
    gpu = torch.cuda.get_device_name(0) if torch.cuda.is_available() else None
    log(f"python {sys.version.split()[0]} torch {torch.__version__} cuda {torch.cuda.is_available()} {gpu or 'no gpu'}")
    if gpu is None:
        raise RuntimeError("no CUDA GPU on this runtime, not training on CPU")
    status("generating data")
    for c in DATA_CMDS:
        if sh(c) != 0:
            raise RuntimeError("data generation failed: " + c)
    for p in sorted(glob.glob("data/*/frames.npy") + glob.glob("data/*/pos.npy") + glob.glob("data/*/actions.npy")):
        log(f"SHA256 {p} {sha(p)}")
    for i, (name, args) in enumerate(JOBS, 1):
        label = f"job {i}/{len(JOBS)} {name}"
        status(label + " training")
        os.makedirs(f"runs/{name}", exist_ok=True)
        train(f"python -m latent_planner.train --out runs/{name} {args} > runs/{name}/stdout.txt 2>&1",
              f"runs/{name}/stdout.txt", label + " training")
        sh(f"tail -3 runs/{name}/stdout.txt")
        status(label + " evaluating")
        for c in EVAL_CMDS:
            sh(c.format(name=name, tag=TAG))
        save_outputs()  # after every job, so a lost VM or timeout still leaves results to fetch
        pack()
        status(label + " done")
    final = "ALL_JOBS_DONE"
except BaseException as e:  # includes a kernel interrupt from `colab restart-kernel` / the web UI
    log(traceback.format_exc())
    final = f"FAILED {type(e).__name__}: {e}"
finally:
    try:
        save_outputs()
        pack()
    except Exception:
        log(traceback.format_exc())
    status(final)
'''


# ----------------------------------------------------------------------------------------------- Colab CLI calls

def colab_env() -> dict:
    env = os.environ.copy()
    env.setdefault("PYTHON_KEYRING_BACKEND", KEYRING_BACKEND)
    env.setdefault("COLUMNS", "160")  # keeps the CLI's tables readable in captured output
    return env


def need_cli() -> None:
    if not COLAB.exists():
        sys.exit(f"Colab CLI not found at {COLAB}. Install it (docs/COLAB.md):\n  uv venv .colab-venv && "
                 "uv pip install --python .colab-venv/bin/python google-colab-cli==0.8.0 keyrings.alt")


def colab(*args: str) -> subprocess.CompletedProcess:
    """One CLI call. stdin is closed, so a missing sign-in fails fast instead of waiting for a pasted code."""
    need_cli()
    r = subprocess.run([str(COLAB), *args], capture_output=True, text=True, stdin=subprocess.DEVNULL,
                       env=colab_env())
    if "authorization code" in r.stderr or "EOFError" in r.stderr:
        sys.exit("Not signed in to Colab. Run: python3 scripts/colab_run.py login   (docs/COLAB.md)")
    return r


def show(r: subprocess.CompletedProcess, tail: int = 2000) -> None:
    for s in (r.stdout.strip(), r.stderr.strip()):
        if s:
            print(s[-tail:])


# ------------------------------------------------------------------------------------------------------- sign-in
# The CLI's own sign-in reads the code from stdin, which a `! command` in Claude Code can't provide. These two steps
# do the same OAuth flow (the CLI's bundled public client, scopes and redirect page, with PKCE) split across two
# commands, and store the token where the CLI looks for it. They run inside .colab-venv, where colab_cli lives.

def _client_config() -> dict:
    custom = Path.home() / ".colab-cli-oauth-config.json"  # the CLI's -c default; else its bundled config
    if custom.exists():
        return json.loads(custom.read_text())
    from importlib import resources
    return json.loads(resources.files("colab_cli").joinpath("oauth_config.json").read_text())


def _login_start() -> None:
    from colab_cli import auth
    from google_auth_oauthlib.flow import InstalledAppFlow
    flow = InstalledAppFlow.from_client_config(_client_config(), auth.PUBLIC_SCOPES)
    flow.redirect_uri = auth.REMOTE_REDIRECT_URI
    url, state = flow.authorization_url(prompt="consent", token_usage="remote")
    JOBS_DIR.mkdir(exist_ok=True)
    LOGIN_PENDING.write_text(json.dumps({"code_verifier": flow.code_verifier, "state": state}))
    LOGIN_PENDING.chmod(0o600)
    print("1. Open this URL in a browser (phone is fine) and sign in with your own Google account:\n")
    print("   " + url + "\n")
    print("2. Approve all the permissions. Google then shows an authorization code.")
    print("3. Run:  python3 scripts/colab_run.py login --code <the code>")


def _login_finish(code: str) -> None:
    import keyring
    from colab_cli import auth
    from google_auth_oauthlib.flow import InstalledAppFlow
    if not LOGIN_PENDING.exists():
        sys.exit("No sign-in in progress. Run `colab_run.py login` first (without --code).")
    pending = json.loads(LOGIN_PENDING.read_text())
    flow = InstalledAppFlow.from_client_config(_client_config(), auth.PUBLIC_SCOPES, state=pending["state"],
                                               code_verifier=pending["code_verifier"], autogenerate_code_verifier=False)
    flow.redirect_uri = auth.REMOTE_REDIRECT_URI
    try:
        flow.fetch_token(code=code.strip())
    except Exception as e:  # noqa: BLE001 (oauthlib raises several types)
        sys.exit(f"Google did not accept the code ({type(e).__name__}: {e}). Codes are single-use and expire after "
                 f"a few minutes: open the URL again for a new one, or run `colab_run.py login` to start over.")
    keyring.set_password(auth.KEYRING_SERVICE_NAME, auth.KEYRING_USERNAME, flow.credentials.to_json())
    LOGIN_PENDING.unlink()
    print(f"Signed in. Token stored with {keyring.get_keyring()}.")
    print("Check it with: python3 scripts/colab_run.py check")


def login(code: str | None) -> None:
    """Re-run this file under .colab-venv's python (which has colab_cli) for the actual OAuth steps."""
    need_cli()
    cmd = [str(COLAB_PY), str(Path(__file__).resolve()), "_login"] + (["--code", code] if code else [])
    sys.exit(subprocess.run(cmd, env=colab_env(), stdin=subprocess.DEVNULL).returncode)


def check() -> None:
    for args in (["sessions"], ["usage"]):
        print(f"$ colab {' '.join(args)}")
        r = colab(*args)
        show(r)
        if r.returncode != 0:
            sys.exit(f"`colab {args[0]}` failed (exit {r.returncode})")


# ---------------------------------------------------------------------------------------------- push/wait/merge

def build(slug: str, jobs: list[tuple[str, str]], tag: str, scene: str) -> Path:
    wd = JOBS_DIR / slug
    wd.mkdir(parents=True, exist_ok=True)
    data_cmds, eval_cmds = (PUSH_DATA, PUSH_EVAL_TUNE) if scene == "push" else (TWOROOM_DATA, TWOROOM_EVAL)
    src = (JOB_TEMPLATE.replace("__PAYLOAD__", payload()).replace("__JOBS__", repr(jobs)).replace("__TAG__", tag)
           .replace("__DATA_CMDS__", repr(data_cmds)).replace("__EVAL_CMDS__", repr(eval_cmds))
           .replace("__STATUS__", REMOTE_STATUS).replace("__TARBALL__", REMOTE_TAR))
    compile(src, str(wd / "script.py"), "exec")  # fail here, not after a GPU has been allocated
    (wd / "script.py").write_text(src)
    (wd / "jobs.json").write_text(json.dumps({"jobs": jobs, "tag": tag, "scene": scene,
                                              "built": time.strftime("%F %T")}, indent=1))
    return wd


def push(slug: str, jobs: list[tuple[str, str]], tag: str, scene: str, gpu: str, dry_run: bool) -> None:
    wd = build(slug, jobs, tag, scene)
    print(f"wrote {wd / 'script.py'} ({(wd / 'script.py').stat().st_size // 1024} KB, {len(jobs)} jobs)")
    if dry_run:
        return
    if colab("status", "-s", slug).returncode == 0:  # `colab new` would silently orphan the running VM
        sys.exit(f"a Colab session named {slug} already exists: wait/stop it, or use another --slug")
    r = colab("new", "-s", slug, "--gpu", gpu)
    show(r)
    if r.returncode != 0:
        sys.exit(f"could not get a {gpu} runtime (free GPUs are not always available; retry later)")
    with open(wd / "exec.log", "w") as log:  # the child keeps its own copy of the file handle
        p = subprocess.Popen([str(COLAB), "exec", "-s", slug, "-f", str(wd / "script.py"), "--timeout", "0"],
                             stdout=log, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, env=colab_env(),
                             start_new_session=True)  # survives this terminal closing
    (wd / "exec.pid").write_text(str(p.pid))
    time.sleep(20)
    if p.poll() is not None:
        print((wd / "exec.log").read_text()[-2000:])
        sys.exit(f"`colab exec` exited early (code {p.returncode}); the VM is still up: "
                 f"colab_run.py stop --slug {slug}")
    print(f"started; cell output -> {wd / 'exec.log'}\nnext: python3 scripts/colab_run.py wait --slug {slug}")


def exec_alive(slug: str) -> bool:
    pid_file = JOBS_DIR / slug / "exec.pid"
    try:
        os.kill(int(pid_file.read_text()), 0)
        return True
    except (OSError, ValueError):
        return False


def fetch(slug: str) -> bool:
    wd = JOBS_DIR / slug
    tgz = wd / "lp_out.tar.gz"
    r = colab("download", "-s", slug, REMOTE_TAR, str(tgz))
    if r.returncode != 0:
        show(r)
        return False
    out = wd / "out"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    with tarfile.open(tgz) as tar:
        tar.extractall(out, filter="data")
    print(f"fetched {tgz.stat().st_size // 1024} KB into {out}: "
          f"{', '.join(sorted(d.name for d in (out / 'runs').glob('*'))) or 'no runs yet'}")
    return True


def wait(slug: str, poll: int, timeout: int, keep: bool) -> str:
    wd = JOBS_DIR / slug
    t0, line, finished, gone = time.time(), "", False, False
    while time.time() - t0 < timeout:
        r = colab("download", "-s", slug, REMOTE_STATUS, str(wd / "status.txt"))
        msg = (r.stdout + r.stderr).strip()
        if f"Session '{slug}' not found" in msg:
            gone = True
            line = "session gone: the VM was stopped or reclaimed by Colab"
        elif r.returncode == 0:
            line = (wd / "status.txt").read_text().strip()
            finished = "ALL_JOBS_DONE" in line or "FAILED" in line
        else:
            line = "no status yet: " + (msg.splitlines()[-1] if msg else f"exit {r.returncode}")
        print(f"[{int(time.time() - t0)}s] {line}  (local exec {'running' if exec_alive(slug) else 'not running'})",
              flush=True)
        if finished or gone:
            break
        time.sleep(poll)
    if gone:
        print("nothing more to fetch; earlier output (if any) is in", wd / "out")
        return line
    fetched = fetch(slug)
    if finished and fetched and not keep:
        r = colab("stop", "-s", slug)
        show(r)
    elif not finished:
        print(f"still running (or status unknown); the VM is left up. Run wait again, or stop it with "
              f"colab_run.py stop --slug {slug}")
    return line


def merge(slug: str) -> None:
    """Copy the fetched runs into runs/ and append their CSV rows to results/ (skipping rows already there)."""
    out = JOBS_DIR / slug / "out"
    if not out.exists():
        sys.exit(f"{out} not found; run wait first")
    for d in sorted((out / "runs").glob("*")):
        dst = ROOT / "runs" / d.name
        if dst.exists():
            print(f"runs/{d.name} exists locally, not overwriting")
            continue
        shutil.copytree(d, dst)
        print(f"copied runs/{d.name}")
    for name in ["eval.csv", "analysis.csv", "eval_push.csv"]:
        src, dst = out / "results" / name, ROOT / "results" / name
        if not src.exists():
            continue
        have = set(dst.read_text().splitlines()) if dst.exists() else set()
        rows = src.read_text().splitlines()
        new = [r for r in rows[1:] if r not in have]
        header = rows[:1] if not dst.exists() else []  # a fresh results file needs the header
        with open(dst, "a") as f:
            for r in header + new:
                f.write(r + "\n")
        print(f"results/{name}: +{len(new)} rows")
    if (out / "results" / "eval").exists():
        shutil.copytree(out / "results" / "eval", ROOT / "results" / "eval", dirs_exist_ok=True)
    if (out / "colab.log").exists():
        shutil.copy(out / "colab.log", ROOT / "results" / f"colab_{slug}.log")


def stop(slug: str) -> None:
    show(colab("stop", "-s", slug))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("action", choices=["login", "check", "push", "wait", "merge", "stop", "_login"])
    ap.add_argument("--slug", help="job name; also the Colab session name")
    ap.add_argument("--jobs", nargs="*", default=[], help='"name=train args" entries')
    ap.add_argument("--tag", default="main")
    ap.add_argument("--scene", choices=["tworoom", "push"], default="tworoom")
    ap.add_argument("--gpu", default="T4", help="Colab accelerator; T4 is the free one")
    ap.add_argument("--dry-run", action="store_true", help="push: only write colab_jobs/<slug>/script.py")
    ap.add_argument("--poll", type=int, default=60)
    ap.add_argument("--timeout", type=int, default=12 * 3600, help="wait: give up polling after this many seconds")
    ap.add_argument("--keep", action="store_true", help="wait: don't stop the VM after fetching")
    ap.add_argument("--code", help="login: the authorization code Google showed")
    a = ap.parse_args()
    if a.action == "_login":
        _login_finish(a.code) if a.code else _login_start()
        return
    if a.action == "login":
        login(a.code)
    elif a.action == "check":
        check()
    else:
        if not a.slug:
            ap.error("--slug is required")
        if a.action == "push":
            jobs = [tuple(j.split("=", 1)) for j in a.jobs]
            if not jobs or any(len(j) != 2 for j in jobs):
                ap.error('give jobs as --jobs "name=train args" ...')
            push(a.slug, jobs, a.tag, a.scene, a.gpu, a.dry_run)
        elif a.action == "wait":
            print(wait(a.slug, a.poll, a.timeout, a.keep))
        elif a.action == "merge":
            merge(a.slug)
        else:
            stop(a.slug)


if __name__ == "__main__":
    main()
